// i2c_test.h - тест шины I2C (веб «Инфо» -> «Журнал ошибок» -> «Тест I2C»): время обменов K22, SHT40 и тача по фазам,
// ошибки, и на каком чтении K22 готов при разных паузах. На время теста loop() (main.cpp) вызывает I2cTest::loop()
// вместо опроса датчиков и экрана; вентиляторы и веб работают, CO2 для них - из чтений теста.
// Проходы (по I2C_TEST_SESSIONS сеансов каждого датчика, датчики - раз в I2C_TEST_CYCLE_MS):
//   1 - опрос размазан по циклу: K22, SHT40, тач - каждый в своём слоте (I2C_TEST_SPREAD_SLOTS), не пересекаются;
//   2 - как в работе: K22 и SHT40 в начале цикла (SHT40 - в паузе K22), тач - каждые TOUCH_POLL_MS;
//   K22 в проходах 1-2: первое чтение ответа и повторы - через tWAIT мин. (K22_TWAIT_MIN_US), до конца сеанса tS;
//   3 - только K22: первое чтение через I2C_TEST_K22_DELAYS_MS, до I2C_TEST_K22_READS чтений через I2C_TEST_K22_REREAD_MS.
// Отчёт - текст (report()), пока идёт - строка хода теста. Всё - под Cfg::lock() (loop() и веб).
#pragma once
